function x = SineBurstExcitationDerivative(t,f_d,n_d,order)
% Number of time steps
NT = numel(t);

% Time-dependent excitation function: Sine burst signal (modulated by a
% Hann-window)
x = zeros(1,NT);
for i = 1:NT
    if order == 1
        if t(i)<n_d/f_d && t(i) >= 0
            x(i) = 2*f_d*pi*sin((pi*f_d*t(i))/n_d)^2*            ...
                   cos(2*pi*f_d*t(i)) +                          ...
                   (2*f_d*pi*cos((pi*f_d*t(i))/n_d)*             ...
                   sin((pi*f_d*t(i))/n_d)*sin(2*pi*f_d*t(i)))/n_d;
        else
            x(i) = 0;
        end
    elseif order == 2
        if t(i)<n_d/f_d && t(i) >= 0
            x(i) = (2*f_d^2*pi^2*cos((pi*f_d*t(i))/n_d)^2*       ...
                   sin(2*pi*f_d*t(i)))/n_d^2 -                   ...
                   4*f_d^2*pi^2*sin((pi*f_d*t(i))/n_d)^2*        ...
                   sin(2*pi*f_d*t(i)) -                          ...
                   (2*f_d^2*pi^2*sin((pi*f_d*t(i))/n_d)^2*       ...
                   sin(2*pi*f_d*t(i)))/n_d^2 +                   ...
                   (8*f_d^2*pi^2*cos((pi*f_d*t(i))/n_d)*         ...
                   sin((pi*f_d*t(i))/n_d)*cos(2*pi*f_d*t(i)))/n_d;
        else
            x(i) = 0;
        end
    elseif order == 3
        if t(i)<n_d/f_d && t(i) >= 0
            x(i) = (12*f_d^3*pi^3*cos((pi*f_d*t(i))/n_d)^2*         ...
                   cos(2*pi*f_d*t(i)))/n_d^2 -                      ...
                   8*f_d^3*pi^3*sin((pi*f_d*t(i))/n_d)^2*           ...
                   cos(2*pi*f_d*t(i)) -                             ...
                   (12*f_d^3*pi^3*sin((pi*f_d*t(i))/n_d)^2*         ...
                   cos(2*pi*f_d*t(i)))/n_d^2 -                      ...
                   (24*f_d^3*pi^3*cos((pi*f_d*t(i))/n_d)*           ...
                   sin((pi*f_d*t(i))/n_d)*sin(2*pi*f_d*t(i)))/n_d - ...
                   (8*f_d^3*pi^3*cos((pi*f_d*t(i))/n_d)*            ...
                   sin((pi*f_d*t(i))/n_d)*sin(2*pi*f_d*t(i)))/n_d^3;
        else
            x(i) = 0;
        end
    elseif order == 4
    elseif order == 5
    end
end

end