function x = RickerExcitationDerivative(t,f_d,order)
% Number of time steps
NT = numel(t);

% Time-dependent excitation function: Ricker wavelet
t0 = 1/f_d;
x = zeros(1,NT);
for i = 1:NT
    if order == 1
        x(i) =  2*f_d^2*pi^2*exp(-f_d^2*pi^2*(t(i)-t0)^2)*          ...
               (t(i)-t0)*(2*f_d^2*pi^2*t(i)^2-4*f_d^2*pi^2*t(i)*t0+ ...
                          2*f_d^2*pi^2*t0^2-3);
    elseif order == 2
        x(i) =  -2*f_d^2*pi^2*exp(-f_d^2*pi^2*(t(i)-t0)^2)*        ...
               ( 4*f_d^4*pi^4*t(i)^4-16*f_d^4*pi^4*t(i)^3*t0+      ...
                24*f_d^4*pi^4*t(i)^2*t0^2-16*f_d^4*pi^4*t(i)*t0^3+ ...
                 4*f_d^4*pi^4*t0^4-12*f_d^2*pi^2*t(i)^2+           ...
                24*f_d^2*pi^2*t(i)*t0-12*f_d^2*pi^2*t0^2+3);
    elseif order == 3
        x(i) =  4*f_d^4*pi^4*exp(-f_d^2*pi^2*(t(i)-t0)^2)*              ...
               (t(i)-t0)*( 4*f_d^4*pi^4*t(i)^4-16*f_d^4*pi^4*t(i)^3*t0+ ...
                          24*f_d^4*pi^4*t(i)^2*t0^2-                    ...
                          16*f_d^4*pi^4*t(i)*t0^3+4*f_d^4*pi^4*t0^4-    ...
                          20*f_d^2*pi^2*t(i)^2+40*f_d^2*pi^2*t(i)*t0-   ...
                          20*f_d^2*pi^2*t0^2+15);
    elseif order == 4
    elseif order == 5
    end
end

end