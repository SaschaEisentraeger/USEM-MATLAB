function x = BurstExcitationDerivative(t,f_d,order)
% Number of time steps
NT = numel(t);

% Time-dependent excitation function: Burst signal
mu = 4/f_d;
sigma = 1/f_d;
x = zeros(1,NT);
for i = 1:NT
    if order == 1
        x(i) = 2*f_d*pi*exp(-(mu - t(i))^2/(2*sigma^2))*              ...
               cos(2*pi*f_d*t(i)) + (exp(-(mu - t(i))^2/(2*sigma^2))* ...
               sin(2*pi*f_d*t(i))*(2*mu - 2*t(i)))/(2*sigma^2);
    elseif order == 2
        x(i) = (exp(-(mu - t(i))^2/(2*sigma^2))*sin(2*pi*f_d*t(i))*  ...
               (2*mu - 2*t(i))^2)/(4*sigma^4) - (exp(-(mu - t(i))^2/ ...
               (2*sigma^2))*sin(2*pi*f_d*t(i)))/sigma^2 -            ...
               4*f_d^2*pi^2*exp(-(mu - t(i))^2/(2*sigma^2))*         ...
               sin(2*pi*f_d*t(i)) +                                  ...
               (2*f_d*pi*exp(-(mu - t(i))^2/(2*sigma^2))*            ...
               cos(2*pi*f_d*t(i))*(2*mu - 2*t(i)))/sigma^2;
    elseif order == 3
        x(i) = (exp(-(mu - t(i))^2/(2*sigma^2))*sin(2*pi*f_d*t(i))* ...
               (2*mu - 2*t(i))^3)/(8*sigma^6) -                     ...
               8*f_d^3*pi^3*exp(-(mu - t(i))^2/(2*sigma^2))*        ...
               cos(2*pi*f_d*t(i)) -                                 ...
               (exp(-(mu - t(i))^2/(2*sigma^2))*sin(2*pi*f_d*t(i))* ...
               (2*mu - 2*t(i)))/(2*sigma^4) -                       ...
               (exp(-(mu - t(i))^2/(2*sigma^2))*sin(2*pi*f_d*t(i))* ...
               (8*mu - 8*t(i)))/(4*sigma^4) -                       ...
               (6*f_d*pi*exp(-(mu - t(i))^2/(2*sigma^2))*           ...
               cos(2*pi*f_d*t(i)))/sigma^2 -                        ...
               (6*f_d^2*pi^2*exp(-(mu - t(i))^2/(2*sigma^2))*       ...
               sin(2*pi*f_d*t(i))*(2*mu - 2*t(i)))/sigma^2 +        ...
               (3*f_d*pi*exp(-(mu - t(i))^2/(2*sigma^2))*           ...
               cos(2*pi*f_d*t(i))*(2*mu - 2*t(i))^2)/(2*sigma^4);
    elseif order == 4
    elseif order == 5
    end
end

end